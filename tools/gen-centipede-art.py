"""Writes the art and colour classes of Centipede from the designer's file, so the code and the design cannot disagree.

From the repository root:   python tools/gen-centipede-art.py

It reads docs/design/moonpatch-art.md (the palette tables, the six nights and every sprite block) and writes into
src/ProGriddle/Games/Centipede: CentipedeTint, CentipedeLook, CentipedeSprite and CentipedeArt. Those four files are generated:
change the design file and run this again, do not edit them by hand. (The game keeps the name Centipede in its code. The names of
the design, Moonpatch, the Wick, the Gloam and so on, appear only in comments and on the game's page.)

A sprite is kept in CentipedeArt as one string of cells, row by row, one character a cell: '.' is transparent and any other
character stands for a colour of CentipedeTint (see Code below). The painter turns a character back into a colour with a table."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, 'docs', 'design', 'moonpatch-art.md')
OUT = os.path.join(ROOT, 'src', 'ProGriddle', 'Games', 'Centipede')

lines = open(DOC, encoding='utf-8').read().split('\n')

# the characters that stand for colours in a sprite string: letters and digits only, so nothing needs escaping in ABL, and
# upper and lower case differ because the painter reads them with ASC
ALPHABET = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'


def pascal(name):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_ ]+', name.strip()) if p)


def span(start_pat, end_pat):
    a = next(i for i, l in enumerate(lines) if re.match(start_pat, l))
    b = next(i for i in range(a + 1, len(lines)) if re.match(end_pat, lines[i]))
    return lines[a:b]


# ---------------------------------------------------------------- the palette
palette = []   # (Name, hex)
for l in span(r'## 2\. ', r'## 3\. '):
    m = re.match(r'\| ([A-Za-z ]+?) \| `([0-9A-Fa-f]{6})` \|', l)
    if m and m.group(1) != 'Name':
        palette.append((pascal(m.group(1)), m.group(2).upper()))
names = [n for n, _ in palette]
assert len(set(names)) == len(names), 'a colour name is used twice'
tints = names + ['FamilyLight', 'FamilyBody', 'FamilyDeep']
assert len(tints) <= len(ALPHABET), 'more colours than characters'
code_of = {n: ALPHABET[i] for i, n in enumerate(tints)}

# ---------------------------------------------------------------- the six nights
nights = []   # (night name, gloam family, bulb family)
for l in span(r'### 4\.4 ', r'### 4\.5 '):
    m = re.match(r'\| (\d) \| ([A-Z ]+) \| (\w+): .* \| (\w+): .* \|', l)
    if m:
        nights.append((m.group(2), pascal(m.group(3)), pascal(m.group(4))))
assert len(nights) == 6
families = []
for fam in dict.fromkeys([n[1] for n in nights] + [n[2] for n in nights]):
    families.append(fam)
for fam in families:
    assert fam + 'Light' in names and fam in names and fam + 'Deep' in names, fam

# ---------------------------------------------------------------- the sprites
sprites = []   # (Name, w, h, cells, note)
i = 0
while i < len(lines):
    m = re.match(r'#### (\w+)(?:, [A-Z ]+)? \((\d+) x (\d+)\)', lines[i])
    if m:
        name, w, h = pascal(m.group(1)), int(m.group(2)), int(m.group(3))
        j = i + 1
        legend = ''
        while not lines[j].startswith('```'):
            if lines[j].startswith('Legend:'):
                legend = lines[j]
            j += 1
        mapping = {}
        for lm in re.finditer(r'`(.)` ((?:family )?[A-Za-z ]+?)(?= `[0-9A-Fa-f]{6}`|[.,(]|$)', legend):
            letter, what = lm.group(1), lm.group(2).strip()
            if what == 'family Light':
                mapping[letter] = 'FamilyLight'
            elif what == 'family Deep':
                mapping[letter] = 'FamilyDeep'
            elif what == 'family body':
                mapping[letter] = 'FamilyBody'
            else:
                mapping[letter] = pascal(what)
        k = j + 1
        pic = []
        while not lines[k].startswith('```'):
            pic.append(lines[k])
            k += 1
        assert len(pic) == h and all(len(r) == w for r in pic), name
        cells = ''
        for row in pic:
            for ch in row:
                if ch == '.':
                    cells += '.'
                else:
                    tint = mapping.get(ch)
                    assert tint in code_of, '%s: no colour for %s (%s)' % (name, ch, legend)
                    cells += code_of[tint]
        sprites.append((name, w, h, cells))
        i = k
    i += 1
assert len(sprites) > 40, len(sprites)

HEADER = ('/* GENERATED by tools/gen-centipede-art.py from docs/design/moonpatch-art.md. Change the design file and run the script,\n'
          '   never edit this file by hand. */\n')


def write(fname, text):
    with open(os.path.join(OUT, fname), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(text)


# ---------------------------------------------------------------- CentipedeTint
t = HEADER + '/* The single colours of the Centipede look, by name, in the order of the palette of the design. The last three are not\n'
t += '   colours: they stand for the light, body and deep colour of the family of the night in a sprite. */\n'
t += 'ENUM ProGriddle.Games.Centipede.CentipedeTint:\n\n    DEFINE ENUM '
t += '\n                '.join((n + ' = 0') if k == 0 else n for k, n in enumerate(tints))
t += '.\n\nEND ENUM.\n'
write('CentipedeTint.cls', t)

# ---------------------------------------------------------------- CentipedeLook
L = HEADER + '''/* The colours of Centipede, in one place (as CentipedeRules holds the numbers). The look is "Moonlit Bed": jewel colours on a
   deep blue night, with six families of colour that swap partners every wave (the crawler takes one, the obstacles another). */
USING Progress.Lang.*.
USING ProGriddle.Core.*.
USING ProGriddle.Games.Centipede.*.

BLOCK-LEVEL ON ERROR UNDO, THROW.

CLASS ProGriddle.Games.Centipede.CentipedeLook FINAL:

    /* The 0xRRGGBB number of a colour. Throws GridException for one of the three family places, which have no colour of their own. */
    METHOD PUBLIC STATIC INTEGER Colour(INPUT poTint AS CentipedeTint):
        CASE poTint:
'''
for n, h in palette:
    L += '            WHEN CentipedeTint:%s THEN RETURN 0x%s.\n' % (n, h)
L += '''            OTHERWISE UNDO, THROW NEW GridException("Centipede has no colour for " + STRING(poTint)).
        END CASE.
    END METHOD.

    /* How many families of colour there are, and how many nights (a wave uses the night ((wave - 1) mod Nights) + 1). */
    METHOD PUBLIC STATIC INTEGER Families():
        RETURN %d.
    END METHOD.

    METHOD PUBLIC STATIC INTEGER Nights():
        RETURN %d.
    END METHOD.

    /* The name of a family, 1 to Families. */
    METHOD PUBLIC STATIC CHARACTER FamilyName(INPUT piFamily AS INTEGER):
        CASE piFamily:
''' % (len(families), len(nights))
for k, fam in enumerate(families):
    L += '            WHEN %d THEN RETURN "%s".\n' % (k + 1, fam)
L += '''            OTHERWISE UNDO, THROW NEW GridException("There is no colour family " + STRING(piFamily)).
        END CASE.
    END METHOD.

    /* The light (piShade 1), body (2) or deep (3) colour of a family. */
    METHOD PUBLIC STATIC INTEGER FamilyColour(INPUT piFamily AS INTEGER, INPUT piShade AS INTEGER):
        IF piShade < 1 OR piShade > 3 THEN UNDO, THROW NEW GridException("A family has shades 1 to 3, not " + STRING(piShade)).
        CASE piFamily:
'''
for k, fam in enumerate(families):
    L += '            WHEN %d THEN RETURN (IF piShade = 1 THEN Colour(CentipedeTint:%sLight) ELSE IF piShade = 2 THEN Colour(CentipedeTint:%s) ELSE Colour(CentipedeTint:%sDeep)).\n' % (k + 1, fam, fam, fam)
L += '''            OTHERWISE UNDO, THROW NEW GridException("There is no colour family " + STRING(piFamily)).
        END CASE.
    END METHOD.

    /* The family of the crawler on the night of wave piWave (1 or more). */
    METHOD PUBLIC STATIC INTEGER CrawlerFamily(INPUT piWave AS INTEGER):
        IF piWave = ? OR piWave < 1 THEN UNDO, THROW NEW GridException("A wave is 1 or more, not " + STRING(piWave)).
        CASE (piWave - 1) MODULO %d:
''' % len(nights)
for k, (nm, g, b) in enumerate(nights):
    L += '            WHEN %d THEN RETURN %d.\n' % (k, families.index(g) + 1)
L += '''            OTHERWISE RETURN 1.
        END CASE.
    END METHOD.

    /* The family of the obstacles on the night of wave piWave. */
    METHOD PUBLIC STATIC INTEGER BulbFamily(INPUT piWave AS INTEGER):
        IF piWave = ? OR piWave < 1 THEN UNDO, THROW NEW GridException("A wave is 1 or more, not " + STRING(piWave)).
        CASE (piWave - 1) MODULO %d:
''' % len(nights)
for k, (nm, g, b) in enumerate(nights):
    L += '            WHEN %d THEN RETURN %d.\n' % (k, families.index(b) + 1)
L += '''            OTHERWISE RETURN 1.
        END CASE.
    END METHOD.

    /* The name of the night of wave piWave. */
    METHOD PUBLIC STATIC CHARACTER NightName(INPUT piWave AS INTEGER):
        IF piWave = ? OR piWave < 1 THEN UNDO, THROW NEW GridException("A wave is 1 or more, not " + STRING(piWave)).
        CASE (piWave - 1) MODULO %d:
''' % len(nights)
for k, (nm, g, b) in enumerate(nights):
    L += '            WHEN %d THEN RETURN "%s".\n' % (k, nm)
L += '''            OTHERWISE RETURN "".
        END CASE.
    END METHOD.

    /* The character of a colour in a sprite string of CentipedeArt, and the colour a character stands for (a tint, or ? for none). */
    METHOD PUBLIC STATIC CHARACTER CodeOf(INPUT poTint AS CentipedeTint):
        CASE poTint:
'''
for n in tints:
    L += '            WHEN CentipedeTint:%s THEN RETURN "%s".\n' % (n, code_of[n])
L += '''            OTHERWISE RETURN ".".
        END CASE.
    END METHOD.

END CLASS.
'''
write('CentipedeLook.cls', L)

# ---------------------------------------------------------------- CentipedeSprite and CentipedeArt
s = HEADER + '/* The sprites of the Centipede look, by name (an enum, so a sprite has a type and a number). CentipedeArt holds their cells. */\n'
s += 'ENUM ProGriddle.Games.Centipede.CentipedeSprite:\n\n    DEFINE ENUM '
s += '\n                '.join((n + ' = 0') if k == 0 else n for k, (n, _, _, _) in enumerate(sprites))
s += '.\n\nEND ENUM.\n'
write('CentipedeSprite.cls', s)

A = HEADER + '''/* The cells of every sprite of Centipede, one string each, row by row: '.' is a cell with nothing in it and any other character
   is a colour (CentipedeLook:CodeOf says which). Sizes are in Width and Height. The three family characters are the places of
   the family colours, which the painter fills in from the wave. */
USING Progress.Lang.*.
USING ProGriddle.Core.*.
USING ProGriddle.Games.Centipede.*.

BLOCK-LEVEL ON ERROR UNDO, THROW.

CLASS ProGriddle.Games.Centipede.CentipedeArt FINAL:

    /* How many sprites there are. */
    METHOD PUBLIC STATIC INTEGER Count():
        RETURN %d.
    END METHOD.

    /* The width of a sprite in cells. */
    METHOD PUBLIC STATIC INTEGER Width(INPUT poSprite AS CentipedeSprite):
        CASE poSprite:
''' % len(sprites)
for n, w, h, c in sprites:
    A += '            WHEN CentipedeSprite:%s THEN RETURN %d.\n' % (n, w)
A += '''            OTHERWISE UNDO, THROW NEW GridException("Centipede has no sprite " + STRING(poSprite)).
        END CASE.
    END METHOD.

    /* The height of a sprite in cells. */
    METHOD PUBLIC STATIC INTEGER Height(INPUT poSprite AS CentipedeSprite):
        CASE poSprite:
'''
for n, w, h, c in sprites:
    A += '            WHEN CentipedeSprite:%s THEN RETURN %d.\n' % (n, h)
A += '''            OTHERWISE UNDO, THROW NEW GridException("Centipede has no sprite " + STRING(poSprite)).
        END CASE.
    END METHOD.

    /* The cells of a sprite, Width times Height characters. */
    METHOD PUBLIC STATIC CHARACTER Cells(INPUT poSprite AS CentipedeSprite):
        CASE poSprite:
'''
for n, w, h, c in sprites:
    A += '            WHEN CentipedeSprite:%s THEN RETURN "%s".\n' % (n, c)
A += '''            OTHERWISE UNDO, THROW NEW GridException("Centipede has no sprite " + STRING(poSprite)).
        END CASE.
    END METHOD.

END CLASS.
'''
write('CentipedeArt.cls', A)
print('%d colours, %d families, %d sprites' % (len(tints), len(families), len(sprites)))
