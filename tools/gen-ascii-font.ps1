<#
.SYNOPSIS
    Writes src/ProGriddle/Engine/AsciiFont.cls: every printable ASCII character as an 8 x 14 bitmap, plus a few drawn extras.
.DESCRIPTION
    The characters are drawn once, at design time, from Consolas 14 pixels with no smoothing, and the result is kept as hex
    (one byte a row, the left most pixel the top bit, 14 rows a glyph). The extras have codes 127 and up and are drawn by hand
    here: joined wall pieces and a floor dot that sits in the middle of the cell. The file is generated: change this script and
    run it again, never edit the class by hand. Needs no OpenEdge install.
.PARAMETER Check
    Writes nothing and fails if the class on disk is not what this script would generate.
.PARAMETER Preview
    Also saves a picture of every glyph to build/scratch/ascii-font.png.
#>
param([switch]$Check, [switch]$Preview)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$target = Join-Path $root 'src\ProGriddle\Engine\AsciiFont.cls'
$cw = 8; $ch = 14

function New-Rows { return ,(New-Object 'int[]' $ch) }

# a glyph is 14 bytes, one a row
function Get-Drawn([char]$c, $font) {
    $bmp = New-Object System.Drawing.Bitmap $cw, $ch
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::Black)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $g.DrawString([string]$c, $font, [System.Drawing.Brushes]::White, [single]0, [single]-2, [System.Drawing.StringFormat]::GenericTypographic)
    $rows = New-Rows
    for ($y = 0; $y -lt $ch; $y++) {
        for ($x = 0; $x -lt $cw; $x++) {
            if ($bmp.GetPixel($x, $y).R -ge 128) { $rows[$y] = $rows[$y] -bor (0x80 -shr $x) }
        }
    }
    $g.Dispose(); $bmp.Dispose()
    return ,$rows
}

function Get-FromArt([string[]]$art) {
    $rows = New-Rows
    for ($y = 0; $y -lt $ch; $y++) {
        for ($x = 0; $x -lt $cw; $x++) { if ($art[$y][$x] -eq '#') { $rows[$y] = $rows[$y] -bor (0x80 -shr $x) } }
    }
    return ,$rows
}

# the extras: 127 wall across, 128 wall down, 129 to 132 the corners (top left, top right, bottom left, bottom right),
# 133 a dot in the middle of the cell, 134 a solid block, 135 a half shade
$extras = @(
    @('........','........','........','........','........','........','########','########','........','........','........','........','........','........'),
    @('...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...','...##...'),
    @('........','........','........','........','........','........','...#####','...#####','...##...','...##...','...##...','...##...','...##...','...##...'),
    @('........','........','........','........','........','........','#####...','#####...','...##...','...##...','...##...','...##...','...##...','...##...'),
    @('...##...','...##...','...##...','...##...','...##...','...##...','...#####','...#####','........','........','........','........','........','........'),
    @('...##...','...##...','...##...','...##...','...##...','...##...','#####...','#####...','........','........','........','........','........','........'),
    @('........','........','........','........','........','........','...##...','...##...','........','........','........','........','........','........'),
    @('########','########','########','########','########','########','########','########','########','########','########','########','########','########'),
    @('#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#','#.#.#.#.','.#.#.#.#')
)

$font = New-Object System.Drawing.Font('Consolas', [single]14, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$glyphs = New-Object System.Collections.Generic.List[object]
for ($code = 32; $code -le 126; $code++) { $glyphs.Add((Get-Drawn ([char]$code) $font)) }
foreach ($e in $extras) { $glyphs.Add((Get-FromArt $e)) }

function Get-Hex($rows) { return (($rows | ForEach-Object { '{0:X2}' -f $_ }) -join '') }

$last = 32 + $glyphs.Count - 1
$sb = New-Object System.Text.StringBuilder
$null = $sb.AppendLine('/* The characters of the screen as 8 x 14 pixel bitmaps: every printable ASCII character (codes 32 to 126) and a few extras for')
$null = $sb.AppendLine('   the dungeon (127 and up: a wall across, a wall down, four corners, a dot in the middle of the cell, a solid block and a half')
$null = $sb.AppendLine('   shade, named in AsciiExtra). The picture of a glyph is 14 rows of 8 pixels, one byte a row with the left most pixel as the top')
$null = $sb.AppendLine('   bit, kept as 28 hex digits.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('   This file is generated by tools/gen-ascii-font.ps1: change the script and run it again, never edit the class by hand. */')
$null = $sb.AppendLine('USING Progress.Lang.*.')
$null = $sb.AppendLine('USING ProGriddle.Core.*.')
$null = $sb.AppendLine('USING ProGriddle.Engine.*.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('BLOCK-LEVEL ON ERROR UNDO, THROW.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('CLASS ProGriddle.Engine.AsciiFont FINAL:')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* The width and height of a glyph, in pixels. */')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC INTEGER GlyphWidth():')
$null = $sb.AppendLine("        RETURN $cw.")
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC INTEGER GlyphHeight():')
$null = $sb.AppendLine("        RETURN $ch.")
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* The lowest and highest code that has a glyph. */')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC INTEGER FirstCode():')
$null = $sb.AppendLine('        RETURN 32.')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC INTEGER LastCode():')
$null = $sb.AppendLine("        RETURN $last.")
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* True when the code has a glyph of its own. */')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC LOGICAL HasGlyph(INPUT piCode AS INTEGER):')
$null = $sb.AppendLine('        RETURN piCode <> ? AND piCode >= FirstCode() AND piCode <= LastCode().')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* The rows of a glyph as 28 hex digits. A code with no glyph gives the glyph of a question mark. */')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC CHARACTER Rows(INPUT piCode AS INTEGER):')
$null = $sb.AppendLine('        IF NOT HasGlyph(piCode) THEN RETURN SUBSTRING(GlyphBits(), (ASC("?") - FirstCode()) * 28 + 1, 28).')
$null = $sb.AppendLine('        RETURN SUBSTRING(GlyphBits(), (piCode - FirstCode()) * 28 + 1, 28).')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* True when the pixel (piX, piY) of the glyph is on. Throws GridException for a pixel outside the glyph. */')
$null = $sb.AppendLine('    METHOD PUBLIC STATIC LOGICAL PixelOn(INPUT piCode AS INTEGER, INPUT piX AS INTEGER, INPUT piY AS INTEGER):')
$null = $sb.AppendLine('        DEFINE VARIABLE bits AS INTEGER NO-UNDO.')
$null = $sb.AppendLine('        IF piX = ? OR piX < 0 OR piX >= GlyphWidth() OR piY = ? OR piY < 0 OR piY >= GlyphHeight() THEN')
$null = $sb.AppendLine('            UNDO, THROW NEW GridException(SUBSTITUTE("Pixel (&1,&2) is outside a glyph of &3 x &4", piX, piY, GlyphWidth(), GlyphHeight())).')
$null = $sb.AppendLine('        bits = HexByte(SUBSTRING(Rows(piCode), piY * 2 + 1, 2)).')
$null = $sb.AppendLine('        RETURN (TRUNCATE(bits / EXP(2, 7 - piX), 0) MODULO 2) = 1.')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    METHOD PRIVATE STATIC INTEGER HexByte(INPUT pcHex AS CHARACTER):')
$null = $sb.AppendLine('        RETURN (INDEX("0123456789ABCDEF", SUBSTRING(pcHex, 1, 1)) - 1) * 16 + INDEX("0123456789ABCDEF", SUBSTRING(pcHex, 2, 1)) - 1.')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('    /* The glyph table: 28 hex digits for each code from 32 up, in order. */')
$null = $sb.AppendLine('    METHOD PRIVATE STATIC CHARACTER GlyphBits():')
$lines = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $glyphs.Count; $i += 8) {
    $chunk = ''
    for ($j = $i; $j -lt [Math]::Min($i + 8, $glyphs.Count); $j++) { $chunk += (Get-Hex $glyphs[$j]) }
    $lines.Add('"' + $chunk + '"')
}
$null = $sb.Append('        RETURN ')
$null = $sb.Append(($lines -join " +`n            "))
$null = $sb.AppendLine('.')
$null = $sb.AppendLine('    END METHOD.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('END CLASS.')
$text = $sb.ToString() -replace "`r`n", "`n"

if ($Check) {
    $current = [IO.File]::ReadAllText($target) -replace "`r`n", "`n"
    if ($current -ne $text) { Write-Error 'AsciiFont.cls is not what gen-ascii-font.ps1 would write'; exit 1 }
    Write-Host 'AsciiFont.cls is up to date'
    exit 0
}
[IO.File]::WriteAllText($target, $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $target ($($glyphs.Count) glyphs)"

if ($Preview) {
    $perRow = 32
    $rowsN = [Math]::Ceiling($glyphs.Count / $perRow)
    $bmp = New-Object System.Drawing.Bitmap ($perRow * ($cw + 1)), ($rowsN * ($ch + 1))
    $gb = [System.Drawing.Graphics]::FromImage($bmp); $gb.Clear([System.Drawing.Color]::Black); $gb.Dispose()
    for ($i = 0; $i -lt $glyphs.Count; $i++) {
        $ox = ($i % $perRow) * ($cw + 1); $oy = [Math]::Floor($i / $perRow) * ($ch + 1)
        for ($y = 0; $y -lt $ch; $y++) { for ($x = 0; $x -lt $cw; $x++) {
            if (($glyphs[$i][$y] -band (0x80 -shr $x)) -ne 0) { $bmp.SetPixel($ox + $x, $oy + $y, [System.Drawing.Color]::White) }
        } }
    }
    $big = New-Object System.Drawing.Bitmap ($bmp.Width * 3), ($bmp.Height * 3)
    $g2 = [System.Drawing.Graphics]::FromImage($big); $g2.InterpolationMode = 'NearestNeighbor'; $g2.PixelOffsetMode = 'Half'
    $g2.DrawImage($bmp, 0, 0, $big.Width, $big.Height)
    $dir = Join-Path $root 'build\scratch'; New-Item -ItemType Directory -Force $dir | Out-Null
    $big.Save((Join-Path $dir 'ascii-font.png'))
}
