"""Writes the art and colour classes of FOR EACH from the designer's file, so the code and the design cannot disagree.

From the repository root:   python tools/gen-foreach-art.py

It reads docs/design/foreach-art.md (the sprite blocks, the 47 wall tiles, the 3 x 5 digits and the two colour tables) and writes
into src/ProGriddle/Games/ForEach: ForEachPicture, ForEachArt, ForEachRow, ForEachTint and ForEachLook. Those five files are
generated: change the design file and run this again, do not edit them by hand."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, 'docs', 'design', 'foreach-art.md')
OUT = os.path.join(ROOT, 'src', 'ProGriddle', 'Games', 'ForEach')

lines = open(DOC, encoding='utf-8').read().split('\n')


def pascal(name):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_ ]+', name.strip()) if p)


def section(start_pat, end_pat):
    """The lines from the first heading that matches start_pat to the next that matches end_pat."""
    a = next(i for i, l in enumerate(lines) if re.match(start_pat, l))
    b = next(i for i in range(a + 1, len(lines)) if re.match(end_pat, lines[i]))
    return lines[a:b]


def hexint(h):
    return int(h, 16)


# ---------------------------------------------------------------- colours
rows = []
for l in section(r'### 1\.1 ', r'### 1\.2 '):
    m = re.match(r'\| (\w+) \| `([0-9A-F]{6})` \| `([0-9A-F]{6})` \| `([0-9A-F]{6})` \| `([0-9A-F]{6})` \| `([0-9A-F]{6})` \|', l)
    if m:
        rows.append((m.group(1), m.groups()[1:]))
tints = []
for l in section(r'### 1\.2 ', r'## 2\. '):
    m = re.match(r'\| ([A-Za-z ]+) \| `([0-9A-F]{6})` \| (.*) \|', l)
    if m and m.group(1) not in ('Name',):
        tints.append((pascal(m.group(1)), m.group(2), m.group(3)))

# ---------------------------------------------------------------- sprites
sprites = []
i = 0
while i < len(lines):
    m = re.match(r'#### (\w+) \((\d+) x (\d+), origin \((\d+), (\d+)\)\)', lines[i])
    if m:
        name, w, h, ox, oy = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4)), int(m.group(5))
        j = i + 1
        legend = ''
        while not lines[j].startswith('```'):
            if lines[j].startswith('Legend:'):
                legend = lines[j]
            j += 1
        k = j + 1
        pic = []
        while not lines[k].startswith('```'):
            pic.append(lines[k])
            k += 1
        assert len(pic) == h and all(len(r) == w for r in pic), (name, len(pic), [len(r) for r in pic])
        tone = re.search(r'tones of \*\*([A-Za-z ]+)\*\*', legend)
        named = re.findall(r'`([A-Z])` ([A-Za-z ]+?) `([0-9A-F]{6})`', legend)
        sprites.append(dict(name=name, w=w, h=h, ox=ox, oy=oy, rows=pic,
                            tone=tone.group(1) if tone else None, legend=','.join('%s=%s' % (c, hx) for c, _, hx in named)))
        i = k
    i += 1

# ---------------------------------------------------------------- digits
d0 = next(i for i, l in enumerate(lines) if l.endswith('The digits:'))
dg = []
j = d0 + 1
while not lines[j].startswith('```'):
    j += 1
j += 1
while not lines[j].startswith('```'):
    dg.append(lines[j])
    j += 1
digits = ['/'.join(r.split('  ')[n] for r in dg) for n in range(10)]
assert all(len(d.split('/')) == 5 and all(len(x) == 3 for x in d.split('/')) for d in digits), digits

# ---------------------------------------------------------------- wall tiles
w0 = next(i for i, l in enumerate(lines) if l.startswith('The 47 wall tiles'))
walls = {}
j = w0 + 1
while not lines[j].startswith('```'):
    j += 1
j += 1
while not lines[j].startswith('```'):
    if re.match(r'm\d+', lines[j]):
        masks = [int(t[1:]) for t in lines[j].split()]
        block = lines[j + 1:j + 9]
        for n, mask in enumerate(masks):
            walls[mask] = '/'.join(r[n * 11:n * 11 + 8] for r in block)
        j += 9
    else:
        j += 1
assert len(walls) == 47, len(walls)

# ---------------------------------------------------------------- writing
BANNER = '/* Generated by tools/gen-foreach-art.py from docs/design/foreach-art.md: do not edit by hand, change the design and run it again. */\n'


def enum(name, doc, members):
    body = '\n                '.join(members)
    return '%s%s\nENUM ProGriddle.Games.ForEach.%s:\n\n    DEFINE ENUM %s\n    .\n\nEND ENUM.\n' % (BANNER, doc, name, '')


def write(name, text):
    with open(os.path.join(OUT, name + '.cls'), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(text)


def enum_text(name, doc, members):
    first = members[0]
    rest = ''.join('\n                %s' % m for m in members[1:])
    return ('%s%s\nENUM ProGriddle.Games.ForEach.%s:\n\n    DEFINE ENUM %s = 1%s.\n\nEND ENUM.\n' % (BANNER, doc, name, first, rest))


pictures = [pascal(s['name']) for s in sprites]
write('ForEachPicture', enum_text('ForEachPicture',
      '/* The pictures of FOR EACH, by name: every sprite block of the design file (section 3), such as DibbyClosed or PhantomBody1. ForEachArt\n   says what each one looks like. */', pictures))
write('ForEachRow', enum_text('ForEachRow',
      '/* The colour rows of FOR EACH (section 1.1 of the design): five tones from highlight (1) to edge (5) for Dibby, the four phantoms, the\n   rolled back and flashing looks and steel. ForEachLook gives the tones. */', [r[0] for r in rows]))
write('ForEachTint', enum_text('ForEachTint',
      '/* The named colours of FOR EACH (section 1.2 of the design), such as Floor, Line and Player. ForEachLook gives each one as a number. */',
      [t[0] for t in tints]))

# the colours
look = [BANNER + '''/* The colours of FOR EACH, from the design: the named colours (section 1.2) and the colour rows of five tones (section 1.1). A colour is a whole
   number, 0xRRGGBB. A tone row is five hex colours separated by commas, lightest first, the form Tile:Colourise reads. */
USING Progress.Lang.*.
USING ProGriddle.Core.*.
USING ProGriddle.Engine.*.
USING ProGriddle.Games.ForEach.*.

BLOCK-LEVEL ON ERROR UNDO, THROW.

CLASS ProGriddle.Games.ForEach.ForEachLook FINAL:

    /* The colour of a named colour. */
    METHOD PUBLIC STATIC INTEGER Colour(INPUT poTint AS ForEachTint):
        CASE poTint:
''']
for name, hx, _ in tints:
    look.append('            WHEN ForEachTint:%s THEN RETURN %d.\n' % (name, hexint(hx)))
look.append('''            OTHERWISE UNDO, THROW NEW GridException("A colour cannot be unknown").
        END CASE.
    END METHOD.

    /* The same colour as six hex digits. */
    METHOD PUBLIC STATIC CHARACTER Hex(INPUT poTint AS ForEachTint):
        RETURN ColourMath:ToHex(Colour(poTint)).
    END METHOD.

    /* The five tones of a colour row, lightest first, as hex colours separated by commas. */
    METHOD PUBLIC STATIC CHARACTER Tones(INPUT poRow AS ForEachRow):
        CASE poRow:
''')
for name, five in rows:
    look.append('            WHEN ForEachRow:%s THEN RETURN "%s".\n' % (name, ','.join(five)))
look.append('''            OTHERWISE UNDO, THROW NEW GridException("A colour row cannot be unknown").
        END CASE.
    END METHOD.

    /* One tone (1 to 5) of a colour row as a number. */
    METHOD PUBLIC STATIC INTEGER Tone(INPUT poRow AS ForEachRow, INPUT piTone AS INTEGER):
        IF piTone = ? OR piTone < 1 OR piTone > 5 THEN UNDO, THROW NEW GridException("A tone is 1 to 5").
        RETURN ColourMath:FromHex(ENTRY(piTone, Tones(poRow))).
    END METHOD.

END CLASS.
''')
write('ForEachLook', ''.join(look))

# the art
art = [BANNER + '''/* The pictures of FOR EACH as the design draws them: rows of pixels for Tile (a dot is a pixel left out, 1 to 5 are the tones of the
   picture's colour row and a capital letter is a named colour of its legend), the legend, which colour row the tones belong to
   (unknown for a picture with none, or one drawn in each phantom's own row), and the origin. Also the 47 wall tiles of the maze, by
   mask (section 2.2), and the 3 x 5 digits of the pop-ups (section 3.6). */
USING Progress.Lang.*.
USING ProGriddle.Core.*.
USING ProGriddle.Engine.*.
USING ProGriddle.Games.ForEach.*.

BLOCK-LEVEL ON ERROR UNDO, THROW.

CLASS ProGriddle.Games.ForEach.ForEachArt FINAL:

    /* The rows of a picture, joined with a slash, as Tile reads them. */
    METHOD PUBLIC STATIC CHARACTER Rows(INPUT poPicture AS ForEachPicture):
        CASE poPicture:
''']
for s in sprites:
    art.append('            WHEN ForEachPicture:%s THEN RETURN "%s".\n' % (pascal(s['name']), '/'.join(s['rows'])))
art.append('''            OTHERWISE UNDO, THROW NEW GridException("A picture cannot be unknown").
        END CASE.
    END METHOD.

    /* The named colours of a picture, as "K=140C1C,E=FFFFFF" (empty for none), as Tile:Colourise reads them. */
    METHOD PUBLIC STATIC CHARACTER Legend(INPUT poPicture AS ForEachPicture):
        CASE poPicture:
''')
for s in sprites:
    if s['legend']:
        art.append('            WHEN ForEachPicture:%s THEN RETURN "%s".\n' % (pascal(s['name']), s['legend']))
art.append('''            OTHERWISE RETURN "".
        END CASE.
    END METHOD.

    /* The colour row whose tones the picture uses, or unknown for a picture with no tones. Phantom pictures are drawn in the row of
       the phantom, which the caller chooses. */
    METHOD PUBLIC STATIC ForEachRow ToneRow(INPUT poPicture AS ForEachPicture):
        CASE poPicture:
''')
for s in sprites:
    if s['tone'] and s['tone'] in [r[0] for r in rows]:
        art.append('            WHEN ForEachPicture:%s THEN RETURN ForEachRow:%s.\n' % (pascal(s['name']), s['tone']))
art.append('''            OTHERWISE RETURN ?.
        END CASE.
    END METHOD.

    /* Where the character's position is in the picture: how many pixels in from its left edge. */
    METHOD PUBLIC STATIC INTEGER OriginX(INPUT poPicture AS ForEachPicture):
        CASE poPicture:
''')
for s in sprites:
    art.append('            WHEN ForEachPicture:%s THEN RETURN %d.\n' % (pascal(s['name']), s['ox']))
art.append('''            OTHERWISE UNDO, THROW NEW GridException("A picture cannot be unknown").
        END CASE.
    END METHOD.

    /* How many pixels in from its top edge. */
    METHOD PUBLIC STATIC INTEGER OriginY(INPUT poPicture AS ForEachPicture):
        CASE poPicture:
''')
for s in sprites:
    art.append('            WHEN ForEachPicture:%s THEN RETURN %d.\n' % (pascal(s['name']), s['oy']))
art.append('''            OTHERWISE UNDO, THROW NEW GridException("A picture cannot be unknown").
        END CASE.
    END METHOD.

    /* True when the mask is one of the 47 wall tiles. */
    METHOD PUBLIC STATIC LOGICAL IsWallMask(INPUT piMask AS INTEGER):
        RETURN LOOKUP(STRING(piMask), "%s") > 0.
    END METHOD.

    /* The 8 x 8 wall tile for a mask of the eight neighbours (N 1, E 2, S 4, W 8, NE 16, SE 32, SW 64, NW 128, a corner counting only
       when both its sides are walls), as rows of ".GLAIF" (floor, glow, line, gap, inner, fill) joined with a slash. Throws
       GridException for a number that is not one of the 47. */
    METHOD PUBLIC STATIC CHARACTER WallRows(INPUT piMask AS INTEGER):
        CASE piMask:
''' % ','.join(str(k) for k in sorted(walls)))
for k in sorted(walls):
    art.append('            WHEN %d THEN RETURN "%s".\n' % (k, walls[k]))
art.append('''            OTHERWISE UNDO, THROW NEW GridException("There is no wall tile for mask " + STRING(piMask)).
        END CASE.
    END METHOD.

    /* The 3 x 5 pixels of a digit for the pop-ups: rows joined with a slash, "#" for a pixel and "." for none. */
    METHOD PUBLIC STATIC CHARACTER DigitRows(INPUT piDigit AS INTEGER):
        CASE piDigit:
''')
for n, d in enumerate(digits):
    art.append('            WHEN %d THEN RETURN "%s".\n' % (n, d))
art.append('''            OTHERWISE UNDO, THROW NEW GridException("A digit is 0 to 9").
        END CASE.
    END METHOD.

END CLASS.
''')
write('ForEachArt', ''.join(art))
print('pictures', len(pictures), 'tints', len(tints), 'rows', len(rows), 'wall tiles', len(walls))
