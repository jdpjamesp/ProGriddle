def legend_line(s, rows_note=None):
    parts = []
    used = s.used()
    if any(ch in '12345' for ch in used):
        if rows_note:
            parts.append('`1`-`5` tones of ' + rows_note)
        else:
            parts.append('`1`-`5` tones of **%s**' % s.tone)
    for k in sorted(s.legend):
        if k in used:
            v = s.legend[k]
            parts.append('`%s` %s `%s`' % (k, v, NAMED[v]))
    return ', '.join(parts) if parts else 'none'


def block(s, rows_note=None, extra=None):
    ox, oy = s.origin
    P('#### %s (%d x %d, origin (%d, %d))' % (s.name, s.width, s.height, ox, oy))
    P('')
    if s.note:
        P(s.note + (' ' + extra if extra else ''))
        P('')
    P('Legend: ' + legend_line(s, rows_note) + '.')
    P('')
    P('```')
    for r in s.rows:
        P(r)
    P('```')
    P('')


def row_table(names):
    P('| Row | 1 | 2 | 3 | 4 | 5 | Used for |')
    P('|---|---|---|---|---|---|---|')
    for n in names:
        t = ROWS[n]
        P('| %s | %s | %s |' % (n, ' | '.join('`%s`' % tohex(c) for c in t), ROW_NOTES[n][1]))
    P('')


